    private void updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateActionPerformed
        // TODO add your handling code here:
        String idP = txtID.getText();
        String NomP = txtNom.getText();
        String Tel = txtTel.getText();
        String Age = txtAge.getText();
        String Sexe = txtSexe.getText();
        String Adresse = txtAdresse.getText();   
        String GroupeSanguin = txtGroupeSanguin.getText();
         PatientDAO patientDAO = new PatientDAO();
        boolean result = patientDAO.updatePatient(idP, NomP,Tel, Age, Sexe, Adresse, GroupeSanguin);
        
        if (result) {
            JOptionPane.showMessageDialog(null, "Modification effectuée avec succès !");
            setVisible(false);
            new modifierPatient().setVisible(true);
        } else {
            JOptionPane.showMessageDialog(null, "Erreur lors de la modification.");
        }
    
    }//GEN-LAST:event_updateActionPerformed

