    private void searchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchActionPerformed
        // TODO add your handling code here:
            String idP = txtID.getText();
         try {
                Connection con = Connexion.getCon();
                Statement st=con.createStatement();
                ResultSet rs=st.executeQuery("SELECT * FROM  patient WHERE idP='"+idP+"'");
                if(rs.next()){
                    txtNom.setText(rs.getString(2));
                    txtTel.setText(rs.getString(3));
                    txtAge.setText(rs.getString(4));
                    txtSexe.setText(rs.getString(5));
                    txtAdresse.setText(rs.getString(6));
                    txtGroupeSanguin.setText(rs.getString(7));
                    txtID.setEditable(false);
                }else{
                    JOptionPane.showMessageDialog(null, "l'ID du patient n'éxiste pas");
                }
                 
         } catch (Exception e) {
         }
                
    }//GEN-LAST:event_searchActionPerformed

