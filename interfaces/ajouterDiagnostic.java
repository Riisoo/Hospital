    private void searchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchActionPerformed
        // TODO add your handling code here:
        String idP =jTextField1.getText();
           try {
                ResultSet rs = (ResultSet) PatientDAO.chercherParId(idP);
                Table.setModel(DbUtils.resultSetToTableModel(rs));

                if (!rs.first()) {
                    dontExist.setVisible(true);
                } else {
                    dontExist.setVisible(false);
                    jTextField1.setEditable(false);
                    flag = 1;
                }

                rs.getStatement().getConnection().close(); // On ferme proprement la connexion

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Erreur de Connexion");
                e.printStackTrace();
            }
    }//GEN-LAST:event_searchActionPerformed

