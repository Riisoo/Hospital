    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        // TODO add your handling code here:
         if (flag == 1) {
        String patientID = jTextField1.getText();
        String symptome = jTextField2.getText();
        String diagnostic = jTextField3.getText();
        String medicaments = jTextField4.getText();
        String serviceReq;
        String typeSer;
        
        if (CheckBoxOui.isSelected()) {
            serviceReq = "YES";
            typeSer = (String) Cmb.getSelectedItem();
        } else {
            serviceReq = "NO";
            typeSer = "";
        }
        
        boolean success = PatientreportDAO.savePatientReport(patientID, symptome, diagnostic, medicaments, serviceReq, typeSer);
        
        if (success) {
            JOptionPane.showMessageDialog(null, "Enregistré avec succès");
            setVisible(false);
            new ajouterDiagnostic().setVisible(true);
        } else {
            JOptionPane.showMessageDialog(null, "Erreur d'enregistrement");
        }
    } else {
        JOptionPane.showMessageDialog(null, "L'ID du patient est vide");
    }
    }//GEN-LAST:event_saveActionPerformed

