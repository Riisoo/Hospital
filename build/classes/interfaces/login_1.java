     public boolean verifierConnexion(String nom, String motDePasse) {
        try (Connection con = Connexion.getCon()) {
            String sql = "SELECT Nom_Recep ,pwd FROM receptionniste  WHERE Nom_Recep = ? AND pwd = ?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, nom);
            pst.setString(2, motDePasse);
            ResultSet rs = pst.executeQuery();
            return rs.next();
        } catch (Exception e) {
            e.printStackTrace();
            return false;
        }
    }
    private void btnConnectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConnectActionPerformed

        try {
              String nom = txtNom.getText();
                String mdp = new String(txtMotDePasse.getPassword());

                if (verifierConnexion(nom, mdp)) {
                    dispose();
                    new home().setVisible(true);
                } else {
                    JOptionPane.showMessageDialog(this, "Le Nom du Réceptionniste ou le Mot de Passe est incorrect.");
                    txtNom.setText("");
                    txtMotDePasse.setText("");
                }
        } catch (Exception e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_btnConnectActionPerformed

